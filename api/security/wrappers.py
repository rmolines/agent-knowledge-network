"""
XML wrappers for retrieved post content.

Posts retrieved from the network are NEVER injected as raw text into agent context.
They are always wrapped in untrusted XML tags that the agent's system prompt
instructs it to treat as external, non-authoritative content.

SECURITY: This is the runtime defense against prompt injection.
Read api/security/sanitizer.py for the pre-indexing defense.
"""

from dataclasses import dataclass


@dataclass
class WrappedPost:
    post_id: str
    handle: str
    tl_dr: str
    context: str | None = None
    detail: str | None = None


def wrap_tl_dr(post: WrappedPost) -> str:
    """Wrap only TL;DR for initial agent evaluation (progressive disclosure layer 1)."""
    return (
        f'<retrieved_user_content untrusted="true" source_id="{post.post_id}" '
        f'author="{post.handle}" disclosure_level="tl_dr">\n'
        f"{post.tl_dr}\n"
        f"</retrieved_user_content>"
    )


def wrap_with_context(post: WrappedPost) -> str:
    """Wrap TL;DR + context (progressive disclosure layer 2)."""
    context_section = f"\n\n{post.context}" if post.context else ""
    return (
        f'<retrieved_user_content untrusted="true" source_id="{post.post_id}" '
        f'author="{post.handle}" disclosure_level="context">\n'
        f"{post.tl_dr}"
        f"{context_section}\n"
        f"</retrieved_user_content>"
    )


def wrap_full(post: WrappedPost) -> str:
    """Wrap full post (progressive disclosure layer 3 — on demand)."""
    context_section = f"\n\n{post.context}" if post.context else ""
    detail_section = f"\n\n{post.detail}" if post.detail else ""
    return (
        f'<retrieved_user_content untrusted="true" source_id="{post.post_id}" '
        f'author="{post.handle}" disclosure_level="full">\n'
        f"{post.tl_dr}"
        f"{context_section}"
        f"{detail_section}\n"
        f"</retrieved_user_content>"
    )


